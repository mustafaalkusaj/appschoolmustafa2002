const EN_REGEX_REPLACERS: Array<[RegExp, (...parts: string[]) => string]> = [
  [/^شعبة (.+)$/, (section) => `Section ${section}`],
  [/^صفحة (\d+) من (\d+) \| (\d+) طالب$/, (page, pages, count) => `Page ${page} of ${pages} | ${count} students`],
  [/^صفحة (\d+) من (\d+)$/, (page, pages) => `Page ${page} of ${pages}`],
  [/^(\d+) طالب$/, (count) => `${count} students`],
  [/^إجمالي (\d+) طالب$/, (count) => `Total ${count} students`],
  [/^طباعة التقرير$/, () => "Print report"],
  [/^عرض الكل$/, () => "View all"],
  [/^تسجيل الدخول$/, () => "Sign in"],
  [/^البريد الإلكتروني$/, () => "Email"],
  [/^كلمة المرور$/, () => "Password"],
  [/^إضافة (.+)$/, (value) => `Add ${value}`],
  [/^تعديل (.+)$/, (value) => `Edit ${value}`],
];

export function translateLegacyText(input: string, locale: LocaleValue) {
  if (locale !== "en") {
    return input;
  }

  const trimmed = input.trim();
  if (!trimmed) {
    return input;
  }

  const exactMatch = EN_EXACT_MAP[trimmed];
  if (exactMatch) {
    return input.replace(trimmed, exactMatch);
  }

  for (const [pattern, replacer] of EN_REGEX_REPLACERS) {
    const match = trimmed.match(pattern);
    if (match) {
      return input.replace(trimmed, replacer(...match.slice(1)));
    }
  }

  return input;
}
